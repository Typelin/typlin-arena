export function scenarioFor(state) { return SCENARIOS[state.scenario] || SCENARIOS.build; }
export function approachOf(state) { return state.anchor.x < .34 ? "clear" : state.anchor.x > .66 ? "creative" : "balanced"; }
export function proposalFor(state, reverse = false) {
  const scenario = scenarioFor(state);
  const actual = approachOf(state);
  const key = reverse ? (actual === "creative" ? "clear" : "creative") : actual;
  const mode = { clear: "清楚可行", balanced: "兼顧兩者", creative: "大膽新意" }[key];
  const constrained = state.stage >= 3 || state.stage === 2 && state.scars.length > 0;
  const branch = Number.isInteger(state.branch) ? state.branch : -1;
  let pair;
  let route = -1;
  if (key === "creative" && (branch >= 0 || constrained)) {
    route = branch >= 0 ? branch : 0;
    if (state.alternate || reverse) route = (route + 1) % 3;
    pair = scenario.routes[route][constrained ? "after" : "before"];
  } else if (constrained && state.alternate) { route = 2; pair = scenario.routes[route].after; }
  else pair = scenario[key === "clear" ? (constrained ? "clearAfter" : "clear") : key === "balanced" ? (constrained ? "balancedAfter" : "balanced") : "creative"];
  const labels = ["把問題展開，而不是急著給結論", "選一個方向，看看答案有什麼不同", constrained ? "新的条件已進來，答案開始改寫" : "提案尚未經過你的現實", "保留目的，重寫方法", "這一次，共同形成的答案"];
  return { title: pair[0], detail: pair[1], mode, key, constrained, route, routeName: route < 0 ? "尚未選定" : scenario.routeNames[route], label: reverse ? "另一面：未選擇的可能" : labels[state.stage] };
}
