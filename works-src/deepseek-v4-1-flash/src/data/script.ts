let cursor = 0;

export const SENTENCES: Sentence[] = RAW.map((s) => ({
  id: s.id,
  forks: s.forks.map((options) => ({ index: cursor++, sentence: s.id, options })),
}));

export const ALL_FORKS: Fork[] = SENTENCES.flatMap((s) => s.forks);

export const TOTAL_STEPS = ALL_FORKS.length;

/** 三條候選枝，永遠是三個。 */
export const BRANCHES = 3;

/** 3^30 —— 你沒走的路。 */
export const PARALLEL_UNIVERSES = Math.pow(BRANCHES, TOTAL_STEPS);
