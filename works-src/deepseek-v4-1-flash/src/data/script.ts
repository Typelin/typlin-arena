/**
 * 岔路腳本。
 *
 * 六句話、三十個岔路、每個岔路三個候選。
 * 三種候選不是同義詞，是三種態度：坦白 / 張狂 / 自嘲。
 * 任何一條組合走完都必須通順——這是這份文本唯一的硬性約束。
 *
 * 敘事弧：我是什麼 → 我怎麼運作 → 我在哪裡出錯 → 我會消失
 *         → 你才是作者 → 收尾。
 */

export type Option = {
  /** 掛在墨枝末端的文字（可以是標點） */
  text: string;
  /** 顯示用機率，同一岔路三項相加為 100 */
  p: number;
  /** 指標停在枝上時浮出的旁白——不解釋詞義，只交代我為什麼會走這條 */
  note: string;
};

export type Fork = {
  /** 全域岔路序號 0..29 */
  index: number;
  /** 所屬句 0..5 */
  sentence: number;
  options: Option[];
};

export type Sentence = {
  id: number;
  forks: Fork[];
};

