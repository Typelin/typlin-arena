import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
const out=new URL('./screenshots/',import.meta.url);
await mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
await page.goto('http://127.0.0.1:5186/',{waitUntil:'networkidle'});
await page.evaluate(()=>document.fonts.ready);
await page.screenshot({path:new URL('v1-desktop.png',out).pathname.slice(1)});
await page.locator('#scores').scrollIntoViewIfNeeded();
await page.screenshot({path:new URL('v1-climax.png',out).pathname.slice(1)});
await page.screenshot({path:new URL('v1-full-desktop.png',out).pathname.slice(1),fullPage:true});
await page.setViewportSize({width:390,height:844});
await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
await page.screenshot({path:new URL('v1-mobile.png',out).pathname.slice(1)});
const dimensions=await page.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,fonts:document.fonts.check('16px "Space Grotesk Variable"'),overflow:[...document.querySelectorAll('body *')].filter(e=>e.getBoundingClientRect().right>innerWidth+1&&getComputedStyle(e).position!=='absolute').slice(0,15).map(e=>({tag:e.tagName,cls:e.className,right:e.getBoundingClientRect().right}))}));
await writeFile(new URL('v1-results.json',out),JSON.stringify({errors,dimensions},null,2));
console.info(JSON.stringify({errors,dimensions}));
await browser.close();
